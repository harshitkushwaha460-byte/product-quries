    shown = set()
    count = 0

    for chunk, score in results:

        document = chunk.get(
            "source_document",
            "Unknown"
        )

        location = chunk.get(
            "source_location",
            "Unknown"
        )

        chunk_id = chunk.get(
            "chunk_id",
            "Unknown"
        )

        product = chunk.get(
            "product",
            "Unknown"
        )

        chunk_standard = chunk.get(
            "standard",
            chunk.get(
                "is_number",
                "Unknown"
            )
        )

        key = (
            document,
            location
        )

        if key in shown:
            continue

        shown.add(key)

        print(
            f"\n[{count + 1}] {document}"
        )

        print(
            f"    Product  : {product}"
        )

        print(
            f"    Standard : {chunk_standard}"
        )

        print(
            f"    Location : {location}"
        )

        print(
            f"    Chunk    : {chunk_id}"
        )

        print(
            f"    Score    : {score:.4f}"
        )

        count += 1

        if count >= max_sources:
            break





