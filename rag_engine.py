def normalize_typos(text):

    words = text.lower().split()

    corrected_words = []

    for word in words:

        clean_word = re.sub(
            r"[^\w]",
            "",
            word
        )

        if clean_word in TYPO_MAP:

            corrected_words.append(
                TYPO_MAP[clean_word]
            )

        else:

            corrected_words.append(
                word
            )

    return " ".join(
        corrected_words
    )






def detect_product(text):

    text_lower = text.lower()


    sorted_products = sorted(
        PRODUCTS.keys(),
        key=len,
        reverse=True
    )

    for product in sorted_products:

        if product in text_lower:

            return product

    return None






def detect_product_from_chunks(
    results
):

    product_scores = {}

    for chunk, score in results:

        product = chunk.get(
            "product",
            ""
        )

        if not product:
            continue

        product_scores[product] = (
            product_scores.get(
                product,
                0
            ) + score
        )

    if not product_scores:
        return None

    return max(
        product_scores,
        key=product_scores.get
    )






