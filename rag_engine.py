def ask_bis_api(question):
    """
    Run the existing BIS RAG pipeline for an API caller.

    The RAG logic above remains unchanged. This wrapper returns
    structured data instead of printing the interactive CLI output.
    """
    global current_product
    global current_standard

    if not question or not question.strip():
        return {
            "success": False,
            "error": "Question cannot be empty.",
            "answer": None,
            "product": current_product,
            "standard": current_standard,
            "query_type": None,
            "sources": []
        }

    question = question.strip()


    corrected_question = normalize_typos(question)


    detected_product = detect_product(corrected_question)

    if detected_product:
        current_product = detected_product
        current_standard = PRODUCTS[detected_product]


    context_answer = None
    if not detected_product:
        context_answer = handle_context_question(corrected_question)

    if context_answer:
        query_type = detect_query_type(corrected_question)
        return {
            "success": True,
            "answer": context_answer,
            "product": current_product,
            "standard": current_standard,
            "query_type": query_type,
            "sources": []
        }

    query_type = detect_query_type(corrected_question)

    search_query = rewrite_query(corrected_question)
    search_query = make_product_aware_query(
        search_query,
        query_type
    )

    results = retrieve_chunks(
        search_query,
        top_k=30
    )

    if not current_product:
        inferred_product = detect_product_from_chunks(results)

        if inferred_product:
            current_product = inferred_product
            current_standard = PRODUCTS.get(
                inferred_product
            )

    if current_product:
        filtered_results = filter_by_product(
            results,
            current_product
        )

        if filtered_results:
            results = filtered_results

    results = topic_boost(
        results,
        query_type
    )

    if not results:
        answer = (
            "I could not find relevant information "
            "in the available BIS sources."
        )

        conversation_history.append({
            "role": "user",
            "content": question
        })

        conversation_history.append({
            "role": "assistant",
            "content": answer
        })

        return {
            "success": True,
            "answer": answer,
            "product": current_product,
            "standard": current_standard,
            "query_type": query_type,
            "search_query": search_query,
            "sources": []
        }

    best_score = results[0][1]

    answer = generate_answer(
        corrected_question,
        results[:5]
    )

    if answer is None:
        answer = fallback_answer(
            corrected_question,
            results[:8],
            query_type
        )

    sources = []

    for chunk, score in results[:5]:
        document = chunk.get(
            "source_document",
            "Unknown"
        )

        location = chunk.get(
            "source_location",
            "Unknown"
        )

        chunk_id = chunk.get(
            "chunk_id",
            "Unknown"
        )

        product = chunk.get(
            "product",
            "Unknown"
        )

        standard = chunk.get(
            "standard",
            chunk.get(
                "is_number",
                "Unknown"
            )
        )

        sources.append({
            "document": document,
            "location": location,
            "product": product,
            "standard": standard
        })

    source_url = get_source_url(
        current_standard,
        query_type
    )

    if source_url:
        sources.insert(
            0,
            {
                "document": "Official BIS website",
                "location": query_type,
                "product": current_product,
                "standard": current_standard,
                "url": source_url
            }
        )

    conversation_history.append({
        "role": "user",
        "content": question
    })

    conversation_history.append({
        "role": "assistant",
        "content": answer
    })

    return {
        "success": True,
        "answer": answer,
        "product": current_product,
        "standard": current_standard,
        "query_type": query_type,
        "search_query": search_query,
        "best_similarity": round(float(best_score), 4),
        "sources": sources
    }

