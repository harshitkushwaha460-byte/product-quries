def rewrite_query(question):

    global current_product
    global current_standard

    corrected_question = normalize_typos(
        question
    )

    history_text = ""

    for message in conversation_history[-6:]:

        history_text += (
            f"{message['role']}: "
            f"{message['content']}\n"
        )

    context_text = ""

    if current_product:

        context_text += (
            f"Current product: "
            f"{current_product}\n"
        )

    if current_standard:

        context_text += (
            f"Current standard: "
            f"{current_standard}\n"
        )

    prompt = f"""
You are a search-query rewriting component
for a BIS Indian Standards RAG system.

Rewrite the user's question into ONE concise
search query.

Rules:

1. Do NOT answer the question.
2. Preserve the user's intent.
3. Correct obvious spelling mistakes.
4. Use conversation context.
5. Use the current product and standard when relevant.
6. For laboratory questions, include laboratory
   or testing laboratory.
7. For testing questions, include tests,
   testing requirements or test methods.
8. For certification questions, include BIS
   certification, licence or Scheme-I.
9. For application questions, include
   application, Manakonline or documents.
10. For standard questions, include standard,
    specification and the IS number when known.
11. Return ONLY the rewritten search query.

Conversation:
{history_text}

Current context:
{context_text}

User question:
{corrected_question}
"""

    try:

        response = client.chat.completions(
            model="sarvam-105b",
            messages=[
                {
                    "role": "user",
                    "content": prompt
                }
            ]
        )

        content = (
            response
            .choices[0]
            .message
            .content
        )

        if content is None:

            return corrected_question

        rewritten = content.strip()

        if not rewritten:

            return corrected_question

        return rewritten

    except Exception as e:

        print(
            "Query rewrite error:",
            e
        )

        return corrected_question






