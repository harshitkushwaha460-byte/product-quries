def generate_answer(
    question,
    results
):
    global current_product
    global current_standard

    context = build_context(results)
    query_type = detect_query_type(question)

    prompt = f"""
You are BIS Sahayak, an AI assistant for Indian Standards and BIS services.

Answer ONLY using the supplied BIS sources.

Rules:
- Give the direct answer first.
- Do not invent information.
- Do not use outside knowledge.
- Mention the IS number when available.
- Cite factual claims as [Source 1], [Source 2], etc.
- If the sources do not contain the answer, say that it could not be verified.
- Keep the answer concise.
- Do not claim to be BIS.

At the end write:

Sources:
[Source 1] Document, location
[Source 2] Document, location

Current product: {current_product}
Current standard: {current_standard}
Query type: {query_type}

Question:
{question}

BIS source context:
{context}

Answer:
"""

    try:
        response = client.chat.completions(
            model="sarvam-105b",
            messages=[
                {
                    "role": "user",
                    "content": prompt
                }
            ],
            temperature=0.1,
            max_tokens=1000,
            reasoning_effort=None
        )

        content = None

        try:
            choice = response.choices[0]
            message = choice.message

            if hasattr(message, "content"):
                content = message.content
            elif isinstance(message, dict):
                content = message.get("content")

        except Exception as extract_error:
            print(
                "Sarvam response extraction error:",
                repr(extract_error)
            )

        if content is None:
            print("Sarvam returned no content.")
            print("Response type:", type(response))
            print("Response:", repr(response))
            return None

        answer = str(content).strip()

        if not answer:
            print("Sarvam returned empty content.")
            return None

        return answer

    except Exception as e:
        print("Sarvam answer error:", repr(e))
        return None

def structured_fallback(question, results, query_type):
    """
    Source-grounded fallback used only when Sarvam does not return
    a usable answer. It never calls an external/general AI API.

    Prefer chunks relevant to the user's query type.
    """
    if not results:
        return None

    topic_keywords = {
        "standard": [
            "standard", "specification", "scope", "title", "is number"
        ],
        "tests": [
            "test", "testing", "test method", "requirements",
            "sample", "frequency"
        ],
        "labs": [
            "laboratory", "laboratories", "testing laboratory",
            "recognized laboratory", "lab"
        ],
        "certification": [
            "certification", "certified", "licence", "license",
            "scheme", "conformity", "grant of licence"
        ],
        "application": [
            "application", "apply", "manakonline", "form v",
            "documents", "factory visit"
        ],
        "general": []
    }

    keywords = topic_keywords.get(query_type, [])

    best_chunk = None
    best_score = float("-inf")

    for chunk, retrieval_score in results:
        content = chunk.get("content", "").strip()
        if not content:
            continue

        content_lower = content.lower()
        topic_hits = sum(
            1 for keyword in keywords
            if keyword in content_lower
        )

        combined_score = retrieval_score + (0.08 * topic_hits)

        if combined_score > best_score:
            best_score = combined_score
            best_chunk = chunk

    if best_chunk is None:
        return None

    content = best_chunk.get("content", "").strip()
    document = best_chunk.get("source_document", "Unknown")
    location = best_chunk.get("source_location", "Unknown")
    return (
        "Based on the retrieved BIS source information:\n\n"
        f"{content}\n\n"
        f"Source: {document}, {location}"
    )

def fallback_answer(
    question,
    results,
    query_type
):

    if not results:

        return (
            "I could not find relevant information "
            "in the available BIS sources."
        )

    structured = structured_fallback(
        question,
        results,
        query_type
    )

    if structured:

        return structured

    chunk = results[0][0]

    content = chunk.get(
        "content",
        ""
    )

    document = chunk.get(
        "source_document",
        "Unknown"
    )

    location = chunk.get(
        "source_location",
        "Unknown"
    )

    return (
        "I found relevant BIS information, "
        "but the answer generator did not "
        "return a usable response.\n\n"

        f"{content}\n\n"

        f"Source: {document}, {location}"
    )







