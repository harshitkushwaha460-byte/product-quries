def retrieve_chunks(
    query,
    top_k=30
):

    query_embedding = model.encode(
        [query],
        normalize_embeddings=True
    )

    query_embedding = np.array(
        query_embedding
    ).astype("float32")

    scores, indices = index.search(
        query_embedding,
        top_k
    )

    results = []

    for score, idx in zip(
        scores[0],
        indices[0]
    ):

        if idx < 0:
            continue

        results.append(
            (
                chunks[idx],
                float(score)
            )
        )

    return results






def filter_by_product(
    results,
    product
):

    if not product:

        return results

    product_lower = product.lower()

    filtered = []

    for chunk, score in results:

        chunk_product = chunk.get(
            "product",
            ""
        ).lower()

        if product_lower in chunk_product:

            filtered.append(
                (
                    chunk,
                    score
                )
            )

    return filtered






def topic_boost(
    results,
    query_type
):

    topic_keywords = {

        "tests": [
            "test",
            "testing",
            "test method",
            "frequency",
            "sample",
            "requirements"
        ],

        "labs": [
            "laboratory",
            "laboratories",
            "lab",
            "testing laboratory",
            "recognized laboratory"
        ],

        "certification": [
            "certification",
            "licence",
            "license",
            "scheme",
            "conformity"
        ],

        "application": [
            "application",
            "manakonline",
            "form v",
            "documents",
            "apply"
        ],

        "standard": [
            "standard",
            "specification",
            "is number"
        ]
    }

    keywords = topic_keywords.get(
        query_type,
        []
    )

    reranked = []

    for chunk, score in results:

        content = chunk.get(
            "content",
            ""
        ).lower()

        boost = 0.0

        for keyword in keywords:

            if keyword in content:

                boost += 0.05

        reranked.append(
            (
                chunk,
                score + boost
            )
        )

    reranked.sort(
        key=lambda x: x[1],
        reverse=True
    )

    return reranked






