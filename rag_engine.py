def get_source_url(standard, query_type="standard"):
    """
    Return the official BIS URL appropriate to the user's query type.
    URLs are hard-coded rather than generated by the LLM.
    """

    if not standard:
        return None

    key = standard

    if standard.startswith("IS 9873"):
        key = "IS 9873"
    elif standard.startswith("IS 16102"):
        key = "IS 16102"
    elif standard.startswith("IS 10325"):
        key = "IS 10325:2000"
    elif standard.startswith("IS 14543"):
        key = "IS 14543:2024"
    elif standard.startswith("IS 13428"):
        key = "IS 13428:2024"
    elif standard.startswith("IS 4151"):
        key = "IS 4151:2015"
    elif standard.startswith("IS 1011"):
        key = "IS 1011:2002"

    source = SOURCE_URLS.get(key)

    if not source:
        return None

    return source.get(
        query_type,
        source.get("standard")
    )







